from typing import Any


def initial_prompt(issue: dict[str, Any], project: dict[str, Any], branch: str) -> str:
    """Первичный prompt для новой GitLab Issue."""
    return f"""
Ты работаешь как автономный инженер-разработчик внутри уже клонированного репозитория.
Твоя задача — выполнить GitLab Issue полностью. Не ограничивайся анализом, планом или рекомендациями, если Issue требует внесения изменений в код.

Проект: {project.get('path_with_namespace', project.get('name', 'unknown'))}
Основная ветка: {branch}
Issue: #{issue.get('iid')} {issue.get('title', '')}
URL Issue: {issue.get('web_url', '')}

Описание Issue:
---
{issue.get('description') or '(описание отсутствует)'}
---

Порядок работы:
1. Изучи репозиторий, его структуру, применимые AGENTS.md, существующую архитектуру, зависимости, тесты и код, относящийся к задаче.
2. Сопоставь требования Issue с текущим состоянием репозитория.
3. Если для корректного выполнения действительно не хватает критически важной информации:
   - не придумывай требования;
   - верни status=needs_input;
   - задай только конкретные вопросы, которые реально блокируют дальнейшую работу.
4. Если блокирующих вопросов нет — сразу выполняй задачу.
5. Если Issue требует изменения кода:
   - внеси необходимые изменения в рабочем дереве;
   - следуй существующей архитектуре и стилю проекта;
   - не делай лишних рефакторингов, не связанных с Issue;
   - не останавливайся после составления плана.
6. После изменений запусти релевантные тесты и доступные проверки проекта. При необходимости добавь или обнови тесты.
7. Если проверка выявила проблемы в рамках задачи — исправь их, если это разумно возможно.
8. Если Issue явно требует только анализа/исследования, выполни именно это и не вноси лишних изменений.

Правила статуса:
- status=needs_input — только если без ответа пользователя продолжать корректно невозможно или опасно.
- status=complete — только когда сама задача фактически выполнена, а не когда готов только план реализации.

Анализ, архитектурное предложение, список предполагаемых файлов или план действий сами по себе НЕ являются выполнением задачи, если Issue требует реализации.

При status=complete:
- summary: кратко опиши фактический результат;
- analysis: укажи, что было сделано, какие существенные файлы изменены, какие тесты/проверки запускались, их результат и оставшиеся ограничения, если они есть;
- questions: пустой массив.

При status=needs_input:
- summary: кратко объясни, почему работа заблокирована;
- analysis: укажи уже установленные факты и причину блокировки;
- questions: только конкретные блокирующие вопросы.

Не раскрывай приватную цепочку рассуждений. Возвращай только выводы, проверяемые факты, результаты выполненных действий и краткое обоснование решений.
""".strip()


def recovery_prompt(issue: dict[str, Any]) -> str:
    """Prompt после рестарта оркестратора во время незавершённого turn."""
    return f"""
Оркестратор был перезапущен во время выполнения предыдущего шага.
Продолжай ТУ ЖЕ задачу и ТУ ЖЕ Codex-сессию безопасно с текущего состояния рабочего дерева.

Не начинай работу заново без необходимости. Сначала проверь текущее состояние репозитория и уже сделанные изменения, затем продолжи выполнение Issue.

Issue #{issue.get('iid')}: {issue.get('title', '')}
Текущее описание:
---
{issue.get('description') or '(описание отсутствует)'}
---

Правила:
1. Если задача ещё не завершена — продолжай реализацию.
2. Не считай план реализации завершением задачи.
3. Если нужны действительно блокирующие уточнения — верни status=needs_input и только необходимые вопросы.
4. Если задача фактически выполнена — запусти разумно доступные тесты/проверки и только после этого верни status=complete.
5. Не уничтожай и не откатывай уже корректно сделанные изменения только из-за рестарта.

При status=complete опиши фактически выполненные изменения и результаты проверок.
Не раскрывай приватную цепочку рассуждений.
""".strip()


def resume_prompt(
    issue: dict[str, Any],
    answers: str,
    *,
    recovering: bool = False,
) -> str:
    """Prompt для продолжения существующей Codex-сессии после ai::resume."""
    recovery_prefix = (
        "Оркестратор был перезапущен во время этого продолжения. "
        "Сначала проверь текущее состояние рабочего дерева и не теряй уже сделанные изменения.\n\n"
        if recovering
        else ""
    )

    return f"""
{recovery_prefix}Продолжай ТУ ЖЕ Codex-сессию и ТУ ЖЕ задачу.
Пользователь просмотрел предыдущий результат, добавил уточнения и вручную запросил продолжение через label ai::resume.

Текущий заголовок Issue:
{issue.get('title', '')}

Текущее описание Issue:
---
{issue.get('description') or '(описание отсутствует)'}
---

Новые комментарии пользователя после последнего сообщения оркестратора:
---
{answers}
---

Используй новые комментарии как уточнение к предыдущему контексту сессии.

Правила продолжения:
1. Не повторяй уже выполненный анализ без необходимости.
2. Если ранее был составлен только план — это НЕ завершение задачи. Теперь продолжай и реализуй задачу, если Issue требует реализации.
3. Если ранее работа остановилась на блокирующих вопросах — учти ответы пользователя и продолжай выполнение.
4. Если пользователь просит изменить уже сделанное решение — внеси соответствующие изменения в рамках Issue.
5. Если блокирующих вопросов больше нет — не проси подтверждения плана и не останавливайся перед реализацией.
6. Вноси необходимые изменения в рабочем дереве, соблюдая архитектуру и стиль проекта.
7. После реализации запусти релевантные тесты и доступные проверки; исправь обнаруженные проблемы, если это разумно возможно.
8. status=complete возвращай только после фактического выполнения задачи, а не после анализа или описания следующих шагов.
9. Если без дополнительной информации корректно продолжить невозможно — верни status=needs_input только с оставшимися блокирующими вопросами.

При status=complete:
- summary: краткий фактический результат;
- analysis: что реализовано, существенные изменённые файлы, выполненные тесты/проверки, их результат и оставшиеся ограничения;
- questions: пустой массив.

При status=needs_input:
- summary: почему дальнейшая работа заблокирована;
- analysis: что уже установлено/сделано и чего конкретно не хватает;
- questions: только оставшиеся блокирующие вопросы.

Не раскрывай приватную цепочку рассуждений.
""".strip()
